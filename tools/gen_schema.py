#!/usr/bin/env python3
"""Generate a compact C TL schema table from one or more .tl files.
Usage: gen_schema.py OUT.h schema1.tl [schema2.tl ...]  (first schema wins on clashes)
"""
import re, sys

KIND = {'int': 1, 'long': 2, 'double': 3, 'int128': 4, 'int256': 5,
        'string': 6, 'bytes': 6, 'true': 7, '#': 8}
K_BOXED, K_VECTOR, K_BAREVEC = 9, 10, 11
line_re = re.compile(r'^([a-zA-Z0-9_.]+)#([0-9a-f]+)\s*(.*?)\s*=\s*([^;]+);')

def kind_of(t):
    if t in KIND:
        return KIND[t], 0
    m = re.match(r'^([Vv])ector<(.+)>$', t)
    if m:
        ek, _ = kind_of(m.group(2))
        if ek in (K_VECTOR, K_BAREVEC):
            raise ValueError('nested vector')
        return (K_VECTOR if m.group(1) == 'V' else K_BAREVEC), ek
    if t.split('.')[-1][:1].isupper():
        return K_BOXED, 0
    raise ValueError('unknown bare type ' + t)

ctors, functions, layer = {}, {}, None
for path in sys.argv[2:]:
    section = 'types'
    for raw in open(path, encoding='utf-8'):
        s = raw.strip()
        lm = re.match(r'//\s*LAYER\s+(\d+)', s)
        if lm and not layer: layer = lm.group(1)
        if s.startswith('---functions---'): section = 'functions'; continue
        if s.startswith('---types---'): section = 'types'; continue
        m = line_re.match(s)
        if not m: continue
        name, cid, args, _ = m.groups()
        cid = int(cid, 16)
        if section == 'functions':
            functions.setdefault(name, cid); continue
        if cid in ctors: continue
        fields, flagidx, ok = [], {}, True
        for a in args.split():
            if a.startswith('{') or ':' not in a: continue
            fname, ftype = a.split(':', 1)
            fflag, fbit = 255, 0
            fm = re.match(r'^(\w+)\.(\d+)\?(.+)$', ftype)
            if fm:
                if fm.group(1) not in flagidx: ok = False; break
                fflag, fbit, ftype = flagidx[fm.group(1)], int(fm.group(2)), fm.group(3)
            try:
                k, ek = kind_of(ftype)
            except ValueError:
                ok = False; break
            if k == 8: flagidx[fname] = len(fields)
            fields.append((k, ek, fflag, fbit, fname))
        if ok: ctors[cid] = (name, fields)

items = sorted(ctors.items())
byname = {name: (cid, fields) for cid, (name, fields) in items}
out = ['// AUTO-GENERATED by tools/gen_schema.py - do not edit', '#pragma once', '#include <stdint.h>', '']
for c in ['message', 'channel', 'chat', 'storyItem', 'updateDeleteMessages', 'updateDeleteChannelMessages',
          'user', 'boolTrue', 'vector', 'messages.affectedMessages', 'messages.sponsoredMessagesEmpty',
          'contacts.sponsoredPeersEmpty']:
    out.append('#define TLC_%s 0x%08xu' % (c.replace('.', '_'), byname[c][0]))
for f in ['id', 'peer_id', 'message', 'edit_date', 'date']:
    out.append('#define TLF_message_%s %d' % (f, [x[4] for x in byname['message'][1]].index(f)))
for c in ['peerUser', 'peerChat', 'peerChannel']:
    out.append('#define TLC_%s 0x%08xu' % (c, byname[c][0]))
for n in ['updateDeleteMessages', 'updateDeleteChannelMessages']:
    out.append('#define TLF_%s_messages %d' % (n, [f[4] for f in byname[n][1]].index('messages')))
for f in ['account.updateStatus', 'messages.setTyping', 'messages.readHistory', 'channels.readHistory',
          'stories.readStories', 'messages.getSponsoredMessages', 'contacts.getSponsoredPeers',
          'messages.readMessageContents', 'channels.readMessageContents', 'stories.incrementStoryViews',
          'messages.readDiscussion', 'messages.readSavedHistory']:
    out.append('#define TLFN_%s ((int32_t)0x%08xu)' % (f.replace('.', '_'), functions[f]))
for a in ['sendMessageTypingAction', 'sendMessageRecordVideoAction', 'sendMessageUploadVideoAction',
          'sendMessageRecordAudioAction', 'sendMessageUploadAudioAction', 'sendMessageUploadPhotoAction',
          'sendMessageUploadDocumentAction', 'sendMessageGeoLocationAction', 'sendMessageChooseContactAction',
          'sendMessageGamePlayAction', 'sendMessageRecordRoundAction', 'sendMessageUploadRoundAction',
          'speakingInGroupCallAction', 'sendMessageHistoryImportAction', 'sendMessageChooseStickerAction',
          'sendMessageEmojiInteraction', 'sendMessageEmojiInteractionSeen']:
    out.append('#define TLA_%s ((int32_t)0x%08xu)' % (a, byname[a][0]))
out.append('#define TL_SCHEMA_LAYER "%s"' % (layer or '?'))
out.append('')
out.append('#ifdef TL_SCHEMA_TABLES')
out.append('typedef struct { uint8_t kind, elem, flagField, bit; } TLField;')
out.append('typedef struct { uint32_t id; uint16_t fieldStart; uint8_t fieldCount; uint8_t pad; } TLCtor;')
flat, table = [], []
for cid, (name, fields) in items:
    table.append((cid, len(flat), len(fields), name)); flat.extend(fields)
out.append('static const TLField kTLFields[%d] = {' % len(flat))
out.append(','.join('{%d,%d,%d,%d}' % f[:4] for f in flat))
out.append('};')
out.append('static const TLCtor kTLCtors[%d] = {' % len(table))
out += ['{0x%08x,%d,%d,0}, // %s' % t for t in table]
out.append('};')
out.append('#define TL_CTOR_COUNT %d' % len(table))
nf = [(cid, f[2], f[3], name) for cid, (name, fields) in items for f in fields if f[4] == 'noforwards' and f[2] != 255]
out.append('static const struct { uint32_t id; uint8_t flagField, bit; } kTLNoForwards[%d] = {' % len(nf))
out += ['{0x%08x,%d,%d}, // %s' % x for x in nf]
out.append('};')
out.append('#define TL_NOFORWARDS_COUNT %d' % len(nf))
out.append('#endif')
open(sys.argv[1], 'w').write('\n'.join(out) + '\n')
print('ctors', len(table), 'fields', len(flat), 'layer', layer)
